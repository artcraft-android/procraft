    /** 把界面英文文案换成简体中文；没有译文时原样返回。 */
    fun t(s: String): String {
        if (s.isEmpty()) return s
        // 已经是中文、或只是数字与单位（"42%"、"120 px"）时直接返回，省掉查表与逐条匹配
        var ascii = false
        for (c in s) if (c in 'A'..'Z' || c in 'a'..'z') { ascii = true; break }
        if (!ascii) return s
        table[s]?.let { return it }
        for (rule in rules) {
            val m = rule.pattern.matchEntire(s) ?: continue
            return rule.build(m)
        }
        return s
    }
