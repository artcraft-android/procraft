/// The bytes of the stock image a brush file names, if the library holds one by that name: the
/// path's last part, case aside.
pub fn stock_image_bytes(name: &str) -> Option<&'static [u8]> {
    let base = name.rsplit(['/', '\\']).next().unwrap_or(name).to_lowercase();
    IMAGES.binary_search_by_key(&base.as_str(), |&(n, _)| n).ok().and_then(|i| IMAGES.get(i)).map(|&(_, bytes)| bytes)
}

/// The image a stand-in's key names (the stock tables hash the file's name the same way), with its
/// name as the table keeps it: the stock library's own brushes name no image, only the key.
pub fn stock_image_by_key(key: u64) -> Option<(&'static str, &'static [u8])> {
    IMAGES.iter().find(|&&(n, _)| crate::textures::stock_key(n) == key).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stock_images_are_found_by_name_whatever_its_case_or_path() {
        assert!(stock_image_bytes("Brush-Preset-Ink-Sponge.png").is_some());
        assert!(stock_image_bytes("folder/BRUSH-POCKET-SOFT-WAX.JPG").is_some());
        assert!(stock_image_bytes("no-such-stock.png").is_none());
    }

    #[test]
    fn the_table_is_sorted_by_name() {
        assert!(IMAGES.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
